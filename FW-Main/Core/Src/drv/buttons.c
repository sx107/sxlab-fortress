#include <main.h>
#include <drv/buttons.h>

void buttons_init() {
	// Init the LFO1 button input
	RCC->AHBENR |= RCC_AHBENR_GPIOCEN;
	MODIFY_REG(GPIOC->MODER, GPIO_MODER_MODER10_Msk, (0b00) << GPIO_MODER_MODER10_Pos);
	MODIFY_REG(GPIOC->PUPDR, GPIO_PUPDR_PUPDR10_Msk, (0b01) << GPIO_PUPDR_PUPDR10_Pos);

	// Init the LFO2 button input
	RCC->AHBENR |= RCC_AHBENR_GPIOCEN;
	MODIFY_REG(GPIOC->MODER, GPIO_MODER_MODER11_Msk, (0b00) << GPIO_MODER_MODER11_Pos);
	MODIFY_REG(GPIOC->PUPDR, GPIO_PUPDR_PUPDR11_Msk, (0b01) << GPIO_PUPDR_PUPDR11_Pos);

	// Init the OSC button input
	RCC->AHBENR |= RCC_AHBENR_GPIOCEN;
	MODIFY_REG(GPIOC->MODER, GPIO_MODER_MODER4_Msk, (0b00) << GPIO_MODER_MODER4_Pos);
	MODIFY_REG(GPIOC->PUPDR, GPIO_PUPDR_PUPDR4_Msk, (0b01) << GPIO_PUPDR_PUPDR4_Pos);

	// Init the PROC button input
	RCC->AHBENR |= RCC_AHBENR_GPIOCEN;
	MODIFY_REG(GPIOC->MODER, GPIO_MODER_MODER5_Msk, (0b00) << GPIO_MODER_MODER5_Pos);
	MODIFY_REG(GPIOC->PUPDR, GPIO_PUPDR_PUPDR5_Msk, (0b01) << GPIO_PUPDR_PUPDR5_Pos);
}
