void biquad_init(_biquad_t* filter) {
	filter->mZ1 = 0;
	filter->mZ2 = 0;
}

float biquad_so(_biquad_t* filter, const float x) {
    float acc = filter->b0 * x + filter->mZ1;
    filter->mZ1 = filter->b1 * x + filter->mZ2;
    filter->mZ2 = filter->b2 * x;
    filter->mZ1 -= filter->a1 * acc;
    filter->mZ2 -= filter->a2 * acc;
    return acc;
}

float biquad_fo(_biquad_t* filter, const float x) {
    float acc = filter->b0 * x + filter->mZ1;
    filter->mZ1 = filter->b1 * x;
    filter->mZ1 -= filter->a1 * acc;
    return acc;
}
