void biquad_lpf1(_biquad_t* filter, const float k) {
    const float kp1 = k+1.f;
    const float km1 = k-1.f;
    filter->b0 = filter->b1 = k / kp1;
    filter->a1 = km1 / kp1;
    filter->a2 = filter->b2 = 0.f;
}
void biquad_hpf1(_biquad_t* filter, const float k) {
    const float kp1 = k+1.f;
    const float km1 = k-1.f;
    filter->b0 = 1.f / kp1;
    filter->b1 = -filter->b0;
    filter->a1 = km1 / kp1;
    filter->a2 = filter->b2 = 0.f;
}
void biquad_apf1(_biquad_t* filter, const float k) {
    const float kp1 = k+1.f;
    const float km1 = k-1.f;
    filter->b0 = filter->a1 = km1 / kp1;
    filter->b1 = 1.f;
    filter->a2 = filter->b2 = 0.f;
}

void biquad_lpf2(_biquad_t* filter, const float k, const float q) {
	const float qk2 = q * k * k;
	const float qk2_k_q_r = 1.f / (qk2 + k + q);
	filter->b0 = filter->b2 = qk2 * qk2_k_q_r;
	filter->b1 = 2.f * filter->b0;
	filter->a1 = 2.f * (qk2 - q) * qk2_k_q_r;
	filter->a2 = (qk2 - k + q) * qk2_k_q_r;
}
void biquad_hpf2(_biquad_t* filter, const float k, const float q) {
	const float qk2 = q * k * k;
	const float qk2_k_q_r = 1.f / (qk2 + k + q);
	filter->b0 = filter->b2 = q * qk2_k_q_r;
	filter->b1 = -2.f * filter->b0;
	filter->a1 = 2.f * (qk2 - q) * qk2_k_q_r;
	filter->a2 = (qk2 - k + q) * qk2_k_q_r;
}
void biquad_bpf2(_biquad_t* filter, const float k, const float q) {
    const float qk2 = q * k * k;
    const float qk2_k_q_r = 1.f / (qk2 + k + q);
    filter->b0 = k * qk2_k_q_r;
    filter->b1 = 0.f;
    filter->b2 = -filter->b0;
    filter->a1 = 2.f * (qk2 - q) * qk2_k_q_r;
    filter->a2 = (qk2 - k + q) * qk2_k_q_r;
}
void biquad_npf2(_biquad_t* filter, const float k, const float q) {
    const float qk2 = q * k * k;
    const float qk2_k_q_r = 1.f / (qk2 + k + q);
    filter->b0 = filter->b2 = (qk2 + q) * qk2_k_q_r;
    filter->b1 = filter->a1 = 2.f * (qk2 - q) * qk2_k_q_r;
    filter->a2 = (qk2 - k + q) * qk2_k_q_r;
}
void biquad_dc2(_biquad_t* filter, const float pole) {
	filter->b0 = filter->b2 = 1.f;
	filter->b1 = 2.f;
	filter->a1 = -2.f * pole;
	filter->a2 = pole * pole;
}
void biquad_apf2(_biquad_t* filter, const float k, const float q) {
    const float qk2 = q * k * k;
    const float qk2_k_q_r = 1.f / (qk2 + k + q);
    filter->b0 = filter->a2 = (qk2 - k + q) * qk2_k_q_r;
    filter->b1 = filter->a1 = 2.f * (qk2 - q) * qk2_k_q_r;
    filter->b2 = 1.f;
}
